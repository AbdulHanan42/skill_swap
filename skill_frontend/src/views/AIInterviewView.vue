<script setup>
import { computed, nextTick, onMounted, onUnmounted, ref, watch } from 'vue'

import { fetchTaskBrief } from '@/api/interviewApi'
import AppLayout from '@/components/common/AppLayout.vue'
import ToastMessage from '@/components/common/ToastMessage.vue'
import InterviewStepTracker from '@/components/interview/InterviewStepTracker.vue'
import McqChallengeCard from '@/components/interview/McqChallengeCard.vue'
import PracticalTaskCard from '@/components/interview/PracticalTaskCard.vue'
import VerificationPanel from '@/components/interview/VerificationPanel.vue'
import { useInterviewStore } from '@/stores/interviewStore'
import { saveBlob } from '@/utils/files'

const store = useInterviewStore()

const toast = ref(null)
const briefBusy = ref(false)
let toastTimer = null

const question = computed(() => store.question)
const task = computed(() => store.task)
const result = computed(() => store.result)
const finished = computed(() => store.finished)
const lockedReason = computed(() => {
  if (store.demo) return 'Reconnect the interview service to file your solution.'
  if (!store.mcqComplete) return 'MCQs must be answered to enable final verify.'
  return ''
})

function notify(text, type = 'info') {
  clearTimeout(toastTimer)
  toast.value = { text, type }
  toastTimer = setTimeout(() => { toast.value = null }, 4200)
}

onMounted(() => {
  if (!store.loadedOnce) store.load()
})

onUnmounted(() => clearTimeout(toastTimer))

watch(
  () => question.value?.id,
  async () => {
    await nextTick()
    window.scrollTo({ top: 0, behavior: 'smooth' })
  },
)

watch(
  () => store.error,
  (message) => { if (message) notify(message, 'error') },
)

async function submitAnswer(option) {
  await store.answer(option)
  if (!store.error) notify(question.value ? 'Answer saved.' : 'Technical round complete — the practical task is unlocked.', 'success')
}

async function skipQuestion() {
  await store.skip()
  if (!store.error) notify('Question skipped.', 'info')
}

async function downloadBrief() {
  if (store.demo) {
    notify('The brief is generated by the backend, which is offline right now.', 'error')
    return
  }
  briefBusy.value = true
  try {
    const blob = await fetchTaskBrief()
    saveBlob(blob, task.value?.brief_filename ?? 'Task_Brief.pdf')
  } catch (err) {
    notify(err?.message ?? 'Could not download the brief.', 'error')
  } finally {
    briefBusy.value = false
  }
}

async function submitSolution(file) {
  await store.submitTask(file)
  if (!store.error) notify('Practical solution filed — verification analysis is ready.', 'success')
}

async function retake() {
  await store.restart()
  if (!store.error) notify('New paper generated from your skills.', 'success')
}
</script>

<template>
  <AppLayout>
    <template #header-sub>
      <p class="mt-1 text-xs text-[var(--text-secondary)]">
        Interview engine: <span class="font-semibold text-[var(--text-primary)]">{{ store.status?.source ?? 'local-bank' }}</span>
        <span class="mx-2 opacity-40">|</span>
        Skills: <span class="font-semibold text-[var(--text-primary)]">{{ store.skillLabel }}</span>
      </p>
    </template>

    <div class="flex flex-col gap-5 xl:flex-row xl:items-start xl:justify-between">
      <div class="max-w-xl">
        <h2 class="text-2xl font-extrabold">AI Skill Interview</h2>
        <p class="mt-1 text-sm text-[var(--text-secondary)]">
          Test your expertise to earn Skill badges and verify
          <span class="font-semibold text-[var(--text-primary)]">{{ store.skillLabel }}</span>
          skills for better matches.
        </p>
      </div>
      <div class="w-full xl:max-w-2xl">
        <InterviewStepTracker
          :step="store.step"
          :answered="store.answered"
          :total-questions="store.totalQuestions"
          :finished="finished"
        />
      </div>
    </div>

    <div v-if="store.demo" class="mt-5 rounded-xl border border-[var(--warning-bg)] bg-[var(--warning-bg)] px-4 py-3 text-xs font-semibold text-[var(--warning-text)]">
      The interview service could not be reached, so this is an offline paper: your answers are kept in the page only and nothing is graded or saved.
      <button type="button" class="ml-2 underline" @click="store.load()">Retry connection</button>
    </div>

    <div v-if="store.loading && !store.status" class="mt-5 grid gap-5 lg:grid-cols-2">
      <div v-for="n in 2" :key="n" class="h-80 animate-pulse rounded-2xl border border-[var(--border-color)] bg-[var(--bg-surface)]"></div>
    </div>

    <Transition enter-active-class="transition duration-300" enter-from-class="opacity-0 translate-y-2">
      <div v-if="finished && result" class="mt-5 grid gap-5 lg:grid-cols-2 lg:items-start">
        <div>
          <h3 class="mb-2 text-lg font-extrabold">Part 3: Verification Analysis</h3>
          <VerificationPanel :result="result" @retake="retake" />
        </div>
        <div>
          <h3 class="mb-2 text-lg font-extrabold">Part 2: Hands-on Practical Task</h3>
          <PracticalTaskCard
            v-if="task"
            :task="task"
            :can-submit="false"
            :submitting="false"
            :busy-brief="briefBusy"
            locked-reason="Your solution is filed with this result."
            @download-brief="downloadBrief"
          />
        </div>
      </div>

      <div v-else class="mt-5 grid gap-5 lg:grid-cols-2 lg:items-start">
        <div>
          <h3 class="mb-2 text-lg font-extrabold">
            Part 1: Quick MCQ Challenge
            <span class="font-semibold text-[var(--text-secondary)]">(Skills: {{ store.skillLabel }})</span>
          </h3>
          <McqChallengeCard
            v-if="question"
            :question="question"
            :skill-label="store.skillLabel"
            :busy="store.loading"
            :demo="store.demo"
            @submit="submitAnswer"
            @skip="skipQuestion"
          />
          <section v-else class="rounded-2xl border border-[var(--border-color)] bg-[var(--bg-surface)] p-5 text-center shadow-sm">
            <div class="mx-auto flex h-11 w-11 items-center justify-center rounded-full bg-[var(--success-bg)] text-[var(--success-text)]">
              <svg class="h-5 w-5" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><path d="M20 6 9 17l-5-5"/></svg>
            </div>
            <h4 class="mt-3 text-sm font-extrabold">Technical round complete</h4>
            <p class="mx-auto mt-1 max-w-xs text-xs text-[var(--text-secondary)]">
              All {{ store.totalQuestions }} questions are answered. Submit the practical task to unlock the verification analysis.
            </p>
            <button
              type="button"
              class="mt-3 rounded-lg border border-[var(--border-color)] bg-[var(--bg-base)] px-3 py-2 text-xs font-bold text-[var(--text-secondary)] transition hover:border-[var(--accent-primary)] hover:text-[var(--accent-primary)]"
              @click="store.restart()"
            >Start a new paper</button>
          </section>
        </div>

        <div>
          <h3 class="mb-2 text-lg font-extrabold">Part 2: Hands-on Practical Task</h3>
          <PracticalTaskCard
            v-if="task"
            :task="task"
            :can-submit="store.mcqComplete"
            :submitting="store.submitting"
            :busy-brief="briefBusy"
            :locked-reason="lockedReason"
            @submit="submitSolution"
            @download-brief="downloadBrief"
          />
          <section v-else class="rounded-2xl border border-dashed border-[var(--border-color)] bg-[var(--bg-surface)] p-5">
            <div class="flex items-center gap-2 text-sm font-extrabold">
              <svg class="h-4 w-4 text-[var(--text-secondary)]" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><rect x="3" y="11" width="18" height="11" rx="2"/><path d="M7 11V7a5 5 0 0 1 10 0v4"/></svg>
              Task unlocks after the technical round
            </div>
            <p class="mt-2 text-xs text-[var(--text-secondary)]">
              Answer the {{ store.totalQuestions }} Python &amp; SQL questions and the brief, the requirements and the upload zone appear here.
            </p>
            <div class="mt-3 space-y-2">
              <div v-for="n in 3" :key="n" class="h-9 animate-pulse rounded-lg bg-[var(--bg-base)]"></div>
            </div>
          </section>
        </div>
      </div>
    </Transition>

    <div class="pointer-events-none fixed inset-x-0 bottom-5 z-50 flex justify-center px-4">
      <div class="pointer-events-auto">
        <ToastMessage
          v-if="toast"
          :message="toast.text"
          :type="toast.type"
          @dismiss="toast = null"
        />
      </div>
    </div>
  </AppLayout>
</template>
